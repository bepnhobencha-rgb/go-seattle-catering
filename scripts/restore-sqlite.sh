#!/bin/bash
# Restore SQLite schema for local dev (after running prepare-deploy.sh).
#
# Usage:  bash scripts/restore-sqlite.sh

set -euo pipefail
cd "$(dirname "$0")/.."

if [ ! -f scripts/schema.sqlite.prisma ]; then
  echo "❌ scripts/schema.sqlite.prisma not found. Did you run prepare-deploy.sh first?"
  exit 1
fi

echo "▶ Restoring SQLite schema"
cp scripts/schema.sqlite.prisma prisma/schema.prisma

echo "▶ Regenerating SQLite migrations"
rm -rf prisma/migrations
mkdir -p prisma/migrations/0_init
npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script > prisma/migrations/0_init/migration.sql
cat > prisma/migrations/migration_lock.toml <<'EOF'
# Please do not edit this file manually
provider = "sqlite"
EOF

echo "▶ Regenerating Prisma client"
npx prisma generate

echo ""
echo "✅ SQLite restored. Run: npm run dev"
